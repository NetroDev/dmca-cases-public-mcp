def build_css():
    data = json.load(open(os.path.join(HERE, 'www-modal-css.json'), encoding='utf-8'))
    parts = []
    for r in data['out']:
        text = r['text']
        for cond in reversed(r['media']):
            text = (cond if cond.startswith('@supports') else '@media ' + cond) + ' {\n' + text + '\n}'
        parts.append(text)
    parts.extend(data['anims'])
    return CSS_HEAD + '\n'.join(parts) + '\n' + CSS_TAIL


def main():
    html = build_html()
    src = open(os.path.join(HERE, 'account-modal.src.js'), encoding='utf-8').read()
    if '__MODAL_HTML__' not in src:
        raise SystemExit('missing __MODAL_HTML__')
    js = src.replace('__MODAL_HTML__', json.dumps(html)).replace('__VERSION__', VERSION)
    js = js.replace(' * Built by tools/account-modal/build.py - edit the source there, not wwwroot/account-modal.js.',
                    ' * Generated by tools/account-modal/build.py from account-modal.src.js - do not edit by hand.')
    with open(os.path.join(OUT, 'account-modal.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    with open(os.path.join(OUT, 'account-modal.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(build_css())
    print('built version', VERSION, len(js), 'bytes js')


if __name__ == '__main__':
    main()
