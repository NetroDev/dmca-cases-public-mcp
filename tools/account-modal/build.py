#!/usr/bin/env python3
"""Build wwwroot/account-modal.{js,css} for mcp.dmca.com.

Inputs (all in this folder):
  www-plan-modal.html   the plan / log in / register modal markup as served on https://www.dmca.com/add/
                        (Add/Assets/pro-comparison-modal.ascx), copied verbatim
  www-modal-css.json    every www.dmca.com CSS rule that styles that modal, captured by extract-css.js
                        (node extract-css.js) and already scoped under #dmcaAcct
  account-modal.src.js  the modal logic (port of PP2020/js/status-upgrade.js without redirects)

Usage: python3 build.py [version]
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'azure', 'DmcaCasesMcp.Functions', 'wwwroot')
VERSION = sys.argv[1] if len(sys.argv) > 1 else '1'


def must_sub(pattern, repl, text, flags=re.S):
    new, n = re.subn(pattern, repl, text, flags=flags)
    if n == 0:
        raise SystemExit('build.py: pattern not found: ' + pattern)
    return new


